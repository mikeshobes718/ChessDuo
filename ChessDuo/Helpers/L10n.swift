import Foundation
import SwiftUI

enum AppLanguage: String, CaseIterable, Identifiable, Codable {
    case system, en, pt, es
    var id: String { rawValue }

    static var resolved: AppLanguage {
        let stored = UserDefaults.standard.string(forKey: "app.language").flatMap(AppLanguage.init) ?? .system
        if stored != .system { return stored }
        let code = Locale.preferredLanguages.first?.prefix(2).lowercased() ?? "en"
        switch code {
        case "pt": return .pt
        case "es": return .es
        default: return .en
        }
    }

    var apiCode: String {
        switch self {
        case .system: return AppLanguage.resolved.apiCode
        case .en: return "en"
        case .pt: return "pt"
        case .es: return "es"
        }
    }

    var title: String {
        switch self {
        case .system: return L10n.t("lang.system")
        case .en: return "English"
        case .pt: return "Português"
        case .es: return "Español"
        }
    }
}

/// Lightweight string table. Keys are looked up in the resolved language, falling back to English.
enum L10n {
    static func t(_ key: String, _ args: CVarArg...) -> String {
        let lang = AppLanguage.resolved
        let table: [String: String]
        switch lang {
        case .pt: table = pt
        case .es: table = es
        default: table = en
        }
        let format = table[key] ?? en[key] ?? key
        return args.isEmpty ? format : String(format: format, arguments: args)
    }

