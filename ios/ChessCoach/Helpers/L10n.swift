enum L10n {
    static func t(_ key: L10nKey, _ args: CVarArg...) -> String {
        let template = table(for: AppLanguage.resolved)[key.rawValue]
            ?? table(for: .english)[key.rawValue]
            ?? key.rawValue
        guard !args.isEmpty else { return template }
        return String(format: template, locale: Locale(identifier: AppLanguage.resolved.rawValue), arguments: args)
    }

    private static func table(for language: AppLanguage) -> [String: String] {
        switch language {
        case .english: return en
        case .portuguese: return pt
        case .spanish: return es
        }
    }

